CREATE TABLE IF NOT EXISTS predictions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    disaster_type VARCHAR(40) NOT NULL,
    latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    location geography(Point, 4326) GENERATED ALWAYS AS (
        ST_SetSRID(ST_MakePoint(longitude, latitude), 4326)::geography
    ) STORED,
    rainfall_mm DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (rainfall_mm >= 0),
    temperature_c DOUBLE PRECISION NOT NULL DEFAULT 25,
    wind_speed_kmh DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (wind_speed_kmh >= 0),
    risk_score DOUBLE PRECISION NOT NULL CHECK (risk_score BETWEEN 0 AND 100),
    risk_level VARCHAR(20) NOT NULL CHECK (risk_level IN ('low', 'moderate', 'high', 'critical')),
    model_version VARCHAR(100),
    explanation JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_predictions_user_id ON predictions (user_id);
CREATE INDEX IF NOT EXISTS ix_predictions_created_at ON predictions (created_at DESC);
CREATE INDEX IF NOT EXISTS ix_predictions_location ON predictions USING GIST (location);
